@unittest.skipUnless(
    os.getenv("RUN_POSTGRES_TESTS") == "1" and os.getenv("RUN_POSTGRES_CONCURRENCY") == "1",
    "Concurrency tests require an isolated test database with CREATE privilege"
)
class ConcurrentStockTests(unittest.TestCase):
    """Separate connections require shared tables in a uniquely named test schema."""

    def setUp(self):
        fixture = PostgresStockTests()
        self.addCleanup(fixture.doCleanups)
        fixture.setUp()
        self.connection = fixture.connection
        self.schema = "inventory_test_" + uuid.uuid4().hex
        with self.connection.transaction():
            self.connection.execute(sql.SQL("CREATE SCHEMA {}").format(sql.Identifier(self.schema)))
        self.addCleanup(self.remove_test_schema)
        with self.connection.transaction():
            for table in ("branches", "products", "inventory", "stock_movements", "stock_requests", "users", "user_sessions", "login_attempts", "stock_transfers", "sales", "daily_reconciliations", "sale_orders", "sale_corrections", "sale_correction_items", "discrepancy_events", "stock_adjustments", "cash_movement_requests", "cash_movements", "customers", "customer_changes", "credit_repayments"):
                self.connection.execute(sql.SQL(
                    "CREATE TABLE {}.{} (LIKE pg_temp.{} INCLUDING ALL)"
                ).format(sql.Identifier(self.schema), sql.Identifier(table), sql.Identifier(table)))
            self.connection.execute(sql.SQL("INSERT INTO {}.branches (id) VALUES (1), (2)").format(sql.Identifier(self.schema)))
            self.connection.execute(sql.SQL("INSERT INTO {}.products (id, is_active) VALUES (1, TRUE), (2, FALSE)").format(sql.Identifier(self.schema)))
            self.connection.execute(sql.SQL("INSERT INTO {}.users (username, password_hash, role) VALUES ('tester', 'unused', 'manager')").format(sql.Identifier(self.schema)))
            self.connection.execute(sql.SQL(
                "INSERT INTO {}.inventory (branch_id, product_id, quantity) VALUES (1, 1, 50)"
            ).format(sql.Identifier(self.schema)))

    def remove_test_schema(self):
        # Only the UUID-named schema created by this test is ever dropped.
        assert self.schema.startswith("inventory_test_") and len(self.schema) == 47
        self.connection.rollback()
        with self.connection.transaction():
            self.connection.execute(sql.SQL("DROP SCHEMA {} CASCADE").format(sql.Identifier(self.schema)))

    def parallel(self, operations):
        barrier = Barrier(len(operations))

        @contextmanager
        def worker_connection():
            with database.get_connection() as connection:
                connection.execute(sql.SQL("SET search_path TO {}").format(sql.Identifier(self.schema)))
                connection.execute("SET statement_timeout TO '10s'")
                connection.commit()
                yield connection

        def request(operation):
            route, body, *key = operation
            with TestClient(main.app, raise_server_exceptions=False) as client:
                barrier.wait(timeout=10)
                response = client.post(route, json=body,
                                       headers={"Idempotency-Key": key[0] if key else str(uuid.uuid4())})
                if route == '/stock-transfers' and response.status_code == 201:
                    confirmed = client.post('/stock-transfers/' + str(response.json()['transfer_id']) + '/confirm')
                    if confirmed.status_code != 200:
                        return confirmed.status_code
                return response.status_code

        with patch.object(main, "db_connection", worker_connection):
            with ThreadPoolExecutor(max_workers=len(operations)) as executor:
                return list(executor.map(request, operations))

    def balances(self):
        with self.connection.transaction():
            return self.connection.execute(sql.SQL(
                "SELECT branch_id, quantity FROM {}.inventory ORDER BY branch_id"
            ).format(sql.Identifier(self.schema))).fetchall()

    def movement_count(self):
        with self.connection.transaction():
            return self.connection.execute(sql.SQL(
                "SELECT COUNT(*) FROM {}.stock_movements"
            ).format(sql.Identifier(self.schema))).fetchone()[0]

    def test_simultaneous_receipts_do_not_lose_increments(self):
        operation = ("/stock-receipts", dict(branch_id=2, product_id=1, quantity=10))
        self.assertEqual(self.parallel([operation] * 4), [201] * 4)
        self.assertEqual(self.balances(), [(1, 50), (2, 40)])
        self.assertEqual(self.movement_count(), 4)

    def test_retired_cash_routes_cannot_post_concurrently(self):
        operation=('/cash-movements',dict(branch_id=1,kind='expense',amount='10',reason='Retired'))
        self.assertEqual(self.parallel([operation]*2),[404,404])
        with self.connection.transaction():
            self.assertEqual(self.connection.execute(sql.SQL('SELECT count(*) FROM {}.cash_movements').format(sql.Identifier(self.schema))).fetchone()[0],0)

    def test_customer_edits_cannot_overwrite_each_other(self):
        self.assertEqual(self.parallel([('/customers', {'branch_id':1,'name':'Original farm'})]), [201])
        with self.connection.transaction():
            customer_id = self.connection.execute(sql.SQL('SELECT id FROM {}.customers').format(sql.Identifier(self.schema))).fetchone()[0]
