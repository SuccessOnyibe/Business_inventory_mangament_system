    def transfer(self, request_key=None, **changes):
        # Existing end-to-end tests complete both dispatch and receiving steps.
        response = self.dispatch(request_key=request_key, **changes)
        if response.status_code == 201:
            confirmation = self.client.post('/stock-transfers/' + str(response.json()['transfer_id']) + '/confirm')
            if confirmation.status_code != 200:
                return confirmation
            response = TestResponse(status_code=201, json={**response.json(), **confirmation.json()})
        return response

